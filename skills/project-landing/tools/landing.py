"""One entry point for the project-landing pipeline.

  python landing.py status                       new / changed project pages on the site vs state/data.json
  python landing.py ingest <slug> [--category C] page + README -> state/data.json (then hand-review)
  python landing.py facts [--only a,b]           GitHub facts -> state/repo_facts.json (merged)
  python landing.py build [--only a,b]           enrich + render -> <out>/p/<slug>/
  python landing.py check [--only a,b]           design-DNA gate + page gates (G1-G8)
  python landing.py shoot a,b [--w 1280 --h 820] screenshots of built pages -> <out>/shots/<w>/
  python landing.py publish [--only a,b] [--push] [-m MSG]
                                                 copy built pages into the site clone, verify protected
                                                 files untouched, commit, optionally push + verify live

Shared options: --site <clone of the github.io repo>  --out <build dir>
Defaults come from state/config.json.
"""
import argparse
import json
import re
import shutil
import subprocess
import sys
import tempfile
import time
import urllib.request
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
SKILL = TOOLS.parent
STATE = SKILL / "state"
PY = sys.executable


def load_config():
    cfg = json.loads((STATE / "config.json").read_text(encoding="utf-8"))
    for key in ("site", "out"):
        path = Path(cfg[key]).expanduser()
        cfg[key] = str(path if path.is_absolute() else SKILL / path)
    if not cfg.get("browser_python") or not Path(cfg["browser_python"]).exists():
        cfg["browser_python"] = sys.executable
    return cfg


def run(cmd, cwd=None, check=True):
    print("$", " ".join(str(c) for c in cmd))
    result = subprocess.run([str(c) for c in cmd], cwd=cwd, text=True, encoding="utf-8", errors="replace",
                            capture_output=True)
    if result.stdout.strip():
        print(result.stdout.strip()[-6000:])
    if result.stderr.strip():
        print(result.stderr.strip()[-3000:])
    if check and result.returncode != 0:
        sys.exit(f"command failed ({result.returncode})")
    return result


def ensure_site(cfg):
    site = Path(cfg["site"])
    if not (site / ".git").exists():
        site.parent.mkdir(parents=True, exist_ok=True)
        run(["git", "clone", f"https://github.com/{cfg['repo']}.git", site])
    else:
        run(["git", "pull", "--ff-only"], cwd=site)
    return site


def data_path():
    return STATE / "data.json"


def load_data():
    return json.loads(data_path().read_text(encoding="utf-8"))


def only_list(value, data):
    return [s for s in (value or "").split(",") if s] or list(data)


def site_slugs(site):
    p_dir = Path(site) / "p"
    return sorted(d.name for d in p_dir.iterdir() if (d / "index.html").exists())


def cmd_status(args, cfg):
    site = ensure_site(cfg)
    data = load_data()
    protected = set(cfg["protected_slugs"])
    new, original_format = [], []
    for slug in site_slugs(site):
        if slug in protected:
            continue
        page = (site / "p" / slug / "index.html").read_text(encoding="utf-8-sig")
        rebuilt = re.search(r'<html[^>]*class="[^"]*\bdna\b', page)
        if slug not in data:
            new.append(slug)
        elif not rebuilt:
            original_format.append(slug)
    print(f"pages in state: {len(data)}")
    print("NEW (not in state yet, ingest these):", new or "none")
    print("REGENERATED by the gallery generator (original format again; re-ingest or rebuild):", original_format or "none")
    missing = [s for s in data if not (site / "p" / s / "index.html").exists()]
    print("in state but gone from the site:", missing or "none")


def cmd_ingest(args, cfg):
    site = ensure_site(cfg)
    cmd = [PY, TOOLS / "ingest.py", data_path(), args.slug, "--site", site, "--state", STATE]
    if args.category:
        cmd += ["--category", args.category]
    if args.readme:
        cmd += ["--readme", args.readme]
    if args.force:
        cmd.append("--force")
    run(cmd)
    print("\nNext: review state/data.json[{0}], add state/content/{0}.json overrides, then add design DNA "
          "for {0} in tools/design.py (FONTS, STYLE, COPY, ART) and a theme in tools/enrich.py.".format(args.slug))


def cmd_facts(args, cfg):
    data = load_data()
    slugs = only_list(args.only, data)
    facts_file = STATE / "repo_facts.json"
    facts = json.loads(facts_file.read_text(encoding="utf-8")) if facts_file.exists() else {}
    with tempfile.TemporaryDirectory() as tmp:
        subset = Path(tmp) / "subset.json"
        out = Path(tmp) / "facts.json"
        subset.write_text(json.dumps({s: data[s] for s in slugs}, ensure_ascii=False), encoding="utf-8")
        run([PY, TOOLS / "repo_facts.py", subset, out])
        facts.update(json.loads(out.read_text(encoding="utf-8")))
    facts_file.write_text(json.dumps(facts, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"repo facts updated for {len(slugs)} slug(s)")


def cmd_build(args, cfg):
    data = load_data()
    slugs = only_list(args.only, data)
    run([PY, TOOLS / "enrich.py", data_path(), STATE / "repo_facts.json"])
    site = Path(cfg["site"])
    for slug in slugs:
        # gallery images are cached in state/gallery; on a fresh machine restore them from the published site
        for g in load_data()[slug].get("gallery") or []:
            cached = STATE / "gallery" / slug / g["file"]
            published = site / "p" / slug / g["file"]
            if not cached.exists() and published.exists():
                cached.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(published, cached)
    out_p = Path(cfg["out"]) / "p"
    with tempfile.TemporaryDirectory() as tmp:
        subset = Path(tmp) / "subset.json"
        subset.write_text(json.dumps({s: load_data()[s] for s in slugs}, ensure_ascii=False), encoding="utf-8")
        run([PY, TOOLS / "build_landing.py", subset, out_p, STATE / "gallery"])
    site = Path(cfg["site"])
    for slug in slugs:
        shot = site / "p" / slug / "shot.jpg"
        if shot.exists():
            shutil.copy2(shot, out_p / slug / "shot.jpg")
    print(f"built {len(slugs)} page(s) -> {out_p}")


def cmd_check(args, cfg):
    data = load_data()
    slugs = only_list(args.only, data)
    dna = run([PY, TOOLS / "dna_check.py", data_path(), "--only", ",".join(slugs)] + (["--fonts"] if args.fonts else []),
              check=False)
    out_p = Path(cfg["out"]) / "p"
    with tempfile.TemporaryDirectory() as tmp:
        new_dir = Path(tmp) / "new"
        old_dir = Path(tmp) / "old"
        for slug in slugs:
            shutil.copytree(out_p / slug, new_dir / slug)
            original = Path(cfg["site"]) / "p" / slug
            if original.exists():
                shutil.copytree(original, old_dir / slug)
        old_dir.mkdir(exist_ok=True)
        result = run([cfg.get("browser_python") or PY, TOOLS / "check.py", old_dir, new_dir], check=False)
    report_path = Path(cfg["out"]) / "check.json"
    report_path.write_text(result.stdout, encoding="utf-8")
    try:
        report = json.loads(result.stdout)
        print(f"gates: {report['pages'] - report['failing_pages']}/{report['pages']} pages pass")
        for slug, fails in report.get("failures", {}).items():
            print("  FAIL", slug, fails)
    except (json.JSONDecodeError, KeyError):
        print("could not parse check.py output; see", report_path)
    if dna.returncode != 0:
        sys.exit("design-DNA gate failed")


def cmd_shoot(args, cfg):
    out_p = Path(cfg["out"]) / "p"
    shots = Path(cfg["out"]) / "shots" / str(args.w)
    targets = [f"{s}={(out_p / s / 'index.html').resolve().as_uri()}" for s in args.slugs.split(",") if s]
    run([cfg.get("browser_python") or PY, TOOLS / "shoot.py", shots, args.w, args.h, "1" if args.full else "0", *targets])
    print("screenshots in", shots)


def cmd_publish(args, cfg):
    site = ensure_site(cfg)
    data = load_data()
    slugs = only_list(args.only, data)
    protected_files = set(cfg["protected_files"])
    protected_slugs = set(cfg["protected_slugs"])
    bad = [s for s in slugs if s in protected_slugs]
    if bad:
        sys.exit(f"refusing to publish protected pages: {bad}")
    out_p = Path(cfg["out"]) / "p"
    for slug in slugs:
        dst = site / "p" / slug
        dst.mkdir(parents=True, exist_ok=True)
        for f in (out_p / slug).iterdir():
            if f.name == "index.html" or re.fullmatch(r"g\d+\.jpg", f.name):
                shutil.copy2(f, dst / f.name)
    status = run(["git", "status", "--porcelain"], cwd=site).stdout.splitlines()
    changed = [line[3:].strip().strip('"') for line in status]
    touched = [p for p in changed if p in protected_files or any(p.startswith(f"p/{s}/") for s in protected_slugs)]
    outside = [p for p in changed if not p.startswith("p/")]
    if touched or outside:
        sys.exit(f"protected or out-of-scope files changed, aborting: {touched + outside}")
    if not changed:
        print("nothing changed")
        return
    print(f"{len(changed)} file(s) changed")
    message = args.message or f"Update landing pages: {', '.join(slugs[:6])}{'…' if len(slugs) > 6 else ''}"
    run(["git", "add", "p"], cwd=site)
    run(["git", "commit", "-q", "-m", message], cwd=site)
    if not args.push:
        print("committed locally; re-run with --push to publish")
        return
    run(["git", "push"], cwd=site)
    commit = run(["git", "log", "-1", "--format=%H"], cwd=site).stdout.strip()
    print(f"pushed https://github.com/{cfg['repo']}/commit/{commit}")
    base = cfg["live_base"].rstrip("/")
    for attempt in range(10):
        ok = []
        for slug in slugs[:5]:
            try:
                page = urllib.request.urlopen(f"{base}/p/{slug}/?cb={int(time.time())}", timeout=20).read().decode("utf-8")
                ok.append("dna h-" in page)
            except Exception:
                ok.append(False)
        if all(ok):
            print(f"live: {len(ok)} checked page(s) serve the new build")
            return
        time.sleep(15)
    print("live site not updated yet (Pages can take a few minutes); re-check later")


def main():
    cfg = load_config()
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--site", default=cfg["site"])
    ap.add_argument("--out", default=cfg["out"])
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("status")
    p = sub.add_parser("ingest")
    p.add_argument("slug")
    p.add_argument("--category")
    p.add_argument("--readme")
    p.add_argument("--force", action="store_true")
    for name in ("facts", "build", "check", "publish"):
        p = sub.add_parser(name)
        p.add_argument("--only", default="")
        if name == "check":
            p.add_argument("--fonts", action="store_true")
        if name == "publish":
            p.add_argument("--push", action="store_true")
            p.add_argument("-m", "--message")
    p = sub.add_parser("shoot")
    p.add_argument("slugs")
    p.add_argument("--w", type=int, default=1280)
    p.add_argument("--h", type=int, default=820)
    p.add_argument("--full", action="store_true")
    args = ap.parse_args()
    cfg["site"] = args.site
    cfg["out"] = args.out
    globals()[f"cmd_{args.cmd}"](args, cfg)


if __name__ == "__main__":
    main()
